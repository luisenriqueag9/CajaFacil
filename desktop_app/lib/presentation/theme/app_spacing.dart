/// Escala oficial de espaciado basada en múltiplos de 4px según CF-DOC-056.
abstract final class AppSpacing {
  static const double xxs = 4.0;   // Spacing-XXS: Micro-separación, badges
  static const double xs = 8.0;    // Spacing-XS: Relleno botones, labels
  static const double s = 12.0;    // Spacing-S: Padding de tablas denso
  static const double m = 16.0;    // Spacing-M: Padding estándar de tarjetas
  static const double l = 24.0;    // Spacing-L: Separación de columnas
  static const double xl = 32.0;   // Spacing-XL: Margen de pantallas
  static const double xxl = 48.0;  // Spacing-XXL: Checkout / Totales
}
